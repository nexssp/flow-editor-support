// Tree-sitter grammar for Nexss Flow editor syntax.
// This grammar is intentionally structural and permissive: the Flow compiler
// is authoritative for semantics, while editors should remain useful as users
// type incomplete or extension-defined actions.
module.exports = grammar({
  name: 'flow',
  extras: $ => [/\s+/, $.comment],
  word: $ => $.identifier,
  externals: $ => [
    $.rust_language_block_content,
    $.language_block_content,
    $.language_inline_double_content,
    $.language_inline_single_content,
    $.language_inline_backtick_content,
  ],
  rules: {
    source_file: $ => repeat(choice(
      $.function_declaration,
      $.schema_declaration,
      $.pipeline_header,
      $.directive_block,
      $.directive,
      $.expression,
      $.modifier,
      $.operator,
      $.punctuation,
      $.raw_char,
    )),

    directive_block: $ => prec(2, seq('@', $.directive_name, optional(':'), $.projection)),
    directive: $ => seq('@', $.directive_name, optional(':')),
    pipeline_header: $ => prec.right(10, seq('@', 'pipeline', $.pipeline_name, repeat($.modifier))),
    pipeline_name: $ => $.identifier,
    schema_declaration: $ => prec(10, seq('@', 'schema', $.schema_name, $.schema_body)),
    schema_name: $ => $.identifier,
    schema_body: $ => seq('{', repeat(choice($.schema_field, $.raw_char)), '}'),
    schema_field: $ => seq(
      $.schema_field_name,
      optional('!'),
      $.schema_field_type,
      optional($.schema_tag),
    ),
    schema_field_name: $ => $.identifier,
    schema_field_type: _ => token(prec(2, /(?:\[\]|map\[[^\]]+\])?\*?[A-Za-z_][A-Za-z0-9_.\/-]*(?:\[[^\]]*\])?/)),
    schema_tag: $ => seq('`', repeat(choice(
      $.schema_tag_key,
      $.schema_tag_value,
      $.schema_tag_text,
    )), '`'),
    schema_tag_key: $ => seq($.schema_tag_key_name, ':'),
    schema_tag_key_name: _ => token(prec(3, /[A-Za-z_][A-Za-z0-9_-]*/)),
    schema_tag_value: _ => token(prec(2, /"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/)),
    schema_tag_text: _ => token(prec(-1, /[^`\s:"']+/)),

    expression: $ => choice($.conditional, $.fallback),
    conditional: $ => prec.right(1, seq(
      $.fallback,
      optional(seq('?', $.fallback, optional(seq(':', $.fallback)))),
    )),
    fallback: $ => prec.left(1, seq($.pipe, repeat(choice(
      seq('||', $.pipe),
      seq('??', $.pipe),
    )))),
    pipe: $ => prec.left(2, seq($.pipeline_step, repeat(seq(choice('->', '|'), $.pipeline_step)))),
    pipeline_step: $ => seq($.parallel, optional($.named_binding)),
    named_binding: $ => seq('as', $.identifier),
    parallel: $ => prec.left(3, seq($.primary, repeat(seq('&', $.primary)))),

    primary: $ => choice(
      $.parallel_block,
      $.race_block,
      $.match_block,
      $.if_block,
      $.each_block,
      $.loop,
      $.language_inline,
      $.language_block,
      $.template_render,
      $.function_call,
      $.atom,
      $.projection,
      $.array,
      $.group,
      $.string,
      $.number,
    ),
    atom: $ => prec.right(seq(
      choice($.identifier_reference, $.path_reference),
      repeat(choice($.modifier, $.prompt, $.targets, $.excludes)),
    )),
    function_call: $ => prec.dynamic(1, seq(
      alias($.identifier_reference, $.function_call_name),
      repeat(choice($.modifier, $.prompt, $.targets, $.excludes)),
      $.argument_list,
    )),

    language_block: $ => prec(20, choice(
      seq(choice('rust', 'rs'), '{', optional($.rust_language_block_content), '}'),
      seq(
        choice('py', 'python', 'py2', 'python2', 'py3', 'python3', 'php', 'typescript', 'ts', 'javascript', 'js', 'go', 'golang'),
        '{',
        optional($.language_block_content),
        '}',
      ),
    )),

    language_inline: $ => prec(20, seq(
      choice('py', 'python', 'py2', 'python2', 'py3', 'python3', 'rust', 'rs', 'php', 'typescript', 'ts', 'javascript', 'js', 'go', 'golang'),
      choice(
        seq('"', optional($.language_inline_double_content), '"'),
        seq("'", optional($.language_inline_single_content), "'"),
        seq('`', optional($.language_inline_backtick_content), '`'),
      ),
    )),

    template_render: $ => prec(20, seq(
      token(prec(2, 'template.render')),
      $.template_render_arguments,
    )),
    template_render_arguments: $ => seq('(', repeat(choice(
      $.template_render_template_field,
      $.spread_field,
      $.projection_field,
      $._block_item,
    )), ')'),
    template_render_template_field: $ => prec(10, seq(
      'template', ':', $.template_string,
    )),

    modifier: $ => prec.right(20, seq(':', $.modifier_name, optional(seq('=', $.modifier_value)))),
    modifier_value: $ => choice($.string, token(/[^\s:(){}&?|,]+/)),
    prompt: $ => prec(2, seq('@', /[^\s:(){}&?|,]+/)),
    targets: $ => prec.right(2, seq('#', $.identifier_reference, repeat(seq(',', $.identifier_reference)))),
    excludes: $ => prec.right(seq('~', $.identifier_reference, repeat(seq(',', $.identifier_reference)))),

    local_binding: $ => prec(5, seq($.binding_keyword, $.identifier, '=', $.expression)),
    binding_keyword: _ => 'let',
    parallel_block: $ => prec(3, seq('parallel', $.projection)),
    race_block: $ => prec(3, seq('race', $.projection)),
    match_block: $ => prec(3, seq('match', optional($.group), $.projection)),
    if_block: $ => prec.right(5, seq(
      'if', $.group, $.projection,
      optional(seq('else', choice($.if_block, $.projection))),
    )),
    each_block: $ => prec(4, seq('each', repeat($.modifier), $.projection)),
    projection: $ => seq('{', repeat(choice($.spread_field, $.projection_field, $._block_item)), '}'),
    projection_field: $ => choice(
      prec(40, seq($.identifier_reference, ':', repeat1($._value_item))),
      $.path_shorthand_field,
    ),
    path_shorthand_field: $ => prec(11, $.path_reference),
    spread_field: $ => prec(3, choice(
      $.input_rooted_spread,
      seq($.spread_operator, $.path_reference),
    )),
    argument_list: $ => prec(4, seq('(', repeat(choice($.projection_field, $.spread_field, $._block_item)), ')')),
    array: $ => seq('[', repeat($._block_item), ']'),
    group: $ => seq('(', repeat($._block_item), ')'),
    loop: $ => seq('loop', '(', repeat($._block_item), ')', 'until', '(', repeat($._block_item), ')'),

    _block_item: $ => choice(
      $.directive_block,
      $.directive,
      $.local_binding,
      $.expression,
      $.modifier,
      $.operator,
      $.punctuation,
      $.raw_char,
    ),
    _value_item: $ => choice(
      $.expression,
      $.modifier,
      $.operator,
      $.punctuation,
      $.raw_char,
    ),

    path_reference: $ => prec.right(2, seq('.', $.identifier, repeat(seq('.', $.identifier)))),
    input_rooted_spread: _ => token(prec(5, /\.\.\.input(?:\.[A-Za-z_][A-Za-z0-9_]*)*/)),
    spread_operator: _ => token(prec(4, '...')),
    identifier: _ => /py\.file|[A-Za-z_][A-Za-z0-9_\/-]*/,
    qualified_identifier: $ => prec.right(8, seq($.identifier, repeat1(seq('.', $.identifier)))),
    identifier_reference: $ => choice($.qualified_identifier, $.identifier),
    modifier_name: $ => /[A-Za-z_][A-Za-z0-9_]*/,
    directive_name: $ => /[A-Za-z_][A-Za-z0-9_.-]*/,
    string: $ => choice(
      /"([^"\\]|\\.)*"/,
      /'([^'\\]|\\.)*'/,
      /`([^`\\]|\\.)*`/,
    ),
    template_string: $ => choice(
      seq(token(prec(1, '"')), repeat(choice(
        $.template_action, $.template_double_text, $.template_brace, $.template_escape,
      )), token(prec(1, '"'))),
      seq(token(prec(1, "'")), repeat(choice(
        $.template_action, $.template_single_text, $.template_brace, $.template_escape,
      )), token(prec(1, "'"))),
      seq(token(prec(1, '`')), repeat(choice(
        $.template_action, $.template_backtick_text, $.template_brace, $.template_escape,
      )), token(prec(1, '`'))),
    ),
    template_action: $ => seq(
      $.template_action_open,
      optional($.template_trim_marker),
      repeat(choice(
        $.template_keyword,
        $.template_variable,
        $.template_dot,
        $.template_identifier,
        $.template_inner_string,
        $.template_operator,
        $.template_action_content,
      )),
      optional($.template_trim_marker),
      $.template_action_close,
    ),
    template_action_open: _ => token(prec(3, '{{')),
    template_action_close: _ => token(prec(3, '}}')),
    template_trim_marker: _ => token(prec(2, '-')),
    template_keyword: _ => token(prec(2, choice(
      'range', 'end', 'if', 'else', 'with', 'template', 'block', 'define', 'break', 'continue',
    ))),
    template_variable: _ => token(prec(3, /\$(?:[A-Za-z_][A-Za-z0-9_]*|\.[A-Za-z_][A-Za-z0-9_]*)|\.[A-Za-z_][A-Za-z0-9_]*/)),
    template_dot: _ => token('.'),
    template_identifier: _ => token(prec(1, /[A-Za-z_][A-Za-z0-9_]*/)),
    template_inner_string: _ => token(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`/),
    template_operator: _ => token(prec(2, choice(':=', '==', '!=', '<=', '>=', '|', ',', ':', '=', '<', '>', '+', '-', '*', '/'))),
    template_action_content: _ => token(prec(-1, /[^{}\s]+/)),
    template_double_text: _ => token(prec(-1, /[^"\\{}]+/)),
    template_single_text: _ => token(prec(-1, /[^'\\{}]+/)),
    template_backtick_text: _ => token(prec(-1, /[^`\\{}]+/)),
    template_brace: _ => token(prec(-1, /[{}]/)),
    template_escape: _ => token(/\\./),
    number: $ => /-?[0-9]+(?:\.[0-9]+)?/,
    operator: $ => choice('->', '||', '&&', '==', '!=', '>=', '<=', '|', '&', '??', '?', '+', '-', '*', '/', '%', '>', '<', '=', '!'),
    punctuation: $ => choice(':', ',', '.', ';', '$'),
    comment: $ => token(seq('//', /[^\n]*/)),
    raw_char: $ => token(prec(-1, /[^\s]/)),
    function_declaration: $ => prec(10, seq(
      '@',
      'func',
      $.function_name,
      '(',
      optional(seq($.function_parameter, repeat(seq(',', $.function_parameter)), optional(','))),
      ')',
      $.function_type,
      choice(
        seq('=', $.expression),
        $.function_body,
      ),
    )),
    function_name: $ => $.identifier_reference,
    function_parameter: $ => seq($.identifier, $.function_type),
    function_type: $ => $.identifier_reference,
    function_body: $ => seq('{', repeat(choice(
      $.local_binding,
      $.expression,
      $.modifier,
      $.operator,
      $.punctuation,
      $.raw_char,
    )), '}'),
  },
});
